export const featuredArticles = articles.filter((article) => article.featured);

export function getArticle(slug: string) {
  const article = articles.find((item) => item.slug === slug);
  if (!article) return undefined;
  const related = articles
    .filter((item) => item.slug !== slug && item.category === article.category)
    .slice(0, 3);
  return { ...article, related };
}

export function searchArticles(query: string, category?: string) {
  const q = query.trim().toLowerCase();
  return articles.filter((article) => {
    const matchesCategory = !category || category === 'all' || article.category === category;
    const matchesQuery =
      !q ||
      `${article.title} ${article.excerpt} ${article.categoryName} ${article.content}`
        .toLowerCase()
        .includes(q);
    return matchesCategory && matchesQuery;
  });
}
